    static void assertCompareTexts(ResourceMatchService service) throws IOException {
        assertCompareText(service, "foo", "bar", new ResourceMatch(
                "target/b.txt",
                ResourceMatchLevel.BUILDABLE,
                """
                        --- target/a.txt
                        +++ target/b.txt
                        @@ -1,1 +1,1 @@
                        -foo
                        +bar
                        """.trim(),
                List.of()));
        assertCompareText(service, "foo\nbar", "foo\r\nbar", new ResourceMatch(
                "target/b.txt",
                ResourceMatchLevel.SUFFICIENT,
                """
                        --- target/a.txt
                        +++ target/b.txt
                        @@ -1,2 +1,2 @@
                        -foo\\r
                        +foo\\r\\n
                         bar
                        """.trim(),
                List.of()));
        assertCompareText(service, "foo\n", "foo\r\n", new ResourceMatch(
                "target/b.txt",
                ResourceMatchLevel.SUFFICIENT,
                """
                        --- target/a.txt
                        +++ target/b.txt
                        @@ -1,1 +1,1 @@
                        -foo\\r
                        +foo\\r\\n
                        """.trim(),
                List.of()));
        assertCompareText(service, "", "", ResourceMatchLevel.PERFECT.match("target/b.txt"));
        assertCompareText(service, "foo", "foo", ResourceMatchLevel.PERFECT.match("target/b.txt"));
        assertCompareText(service, "foo\nbar", "foo\nbar", ResourceMatchLevel.PERFECT.match("target/b.txt"));
        assertCompareText(service, "foo\rbar", "foo\rbar", ResourceMatchLevel.PERFECT.match("target/b.txt"));
        assertCompareText(service, "foo\r\nbar", "foo\r\nbar", ResourceMatchLevel.PERFECT.match("target/b.txt"));

        compareJavaDoc(service);
    }

    @Test
    void javaDocSanitizers() {
        Assertions.assertThat(Sanitizer
                .removeGroup(TextResourceMatchService.JAVADOC_GENERATED_BY_TIMESTAMP_PATTERN, 2)
                .apply("<!-- Generated by javadoc (11.0.25) on Wed Feb 04 20:47:52 CET 2026 -->"))
                .isEqualTo("<!-- Generated by javadoc (11.0.25) on  -->");
        Assertions.assertThat(Sanitizer
                .removeGroup(TextResourceMatchService.JAVADOC_META_TIMESTAMP_PATTERN, 1)
                .apply("<meta name=\"dc.created\" content=\"2026-02-04\">"))
                .isEqualTo("<meta name=\"dc.created\" content=\"\">");

        Assertions.assertThat(Sanitizer
                .removeGroup(TextResourceMatchService.JAVADOC_UNQUALIFY_MEMBER_LABEL, 1)
                .apply("<div class=\"block\"><code>Gav.version</code>"))
                .isEqualTo(
                        "<div class=\"block\"><code>version</code>");

        //                + "      +<!-- Generated by javadoc (11.0.25) on Tue Jul 14 11:35:06 CEST 2026")
    }

